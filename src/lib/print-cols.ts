/**
 * 新增打印件（考勤月表 / 全年月表 / 年度工资汇总 / 人员名单）的列宽（百分比，唯一实现）。
 *
 * 为什么要有这个模块：**打印纸不能横向滚动**，而表格里会出现长文本
 * （考勤备注「春节放假，只出勤几天，其余按事假处理」、加班规则「平时1.5倍/周末2倍」）。
 * 用默认的自动列宽时，这些长文本会把整张表撑得比纸面还宽 → 右侧几列被**静默裁掉**，
 * 用户印出来才发现少了列。所以这几张表都用 `table-layout: fixed` + `<colgroup>`，
 * 让「总宽 = 纸面宽」，长文本在自己格子里换行。两条不变量（`tests/attendance-print.test.ts` 机械校验）：
 *  · 每组的百分比**正好加满 100**（少了右边留空、多了溢出被裁）；
 *  · 单列不低于 4%；这只是序号等短列的下限，不能作为金额可读性的保证。
 * 金额需结合真实纸宽、字号、内边距与合计位数检查，最终以真实 PDF 为准。
 * 组件只 import 这些常量，不许在组件里另写一套（改列宽就改这里一处）。
 */

